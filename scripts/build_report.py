import math
import re
import shutil
import subprocess
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PENDING = r"\pending"
REPORT = ROOT / "report"
GEN = REPORT / "generated"
FIG = REPORT / "figures"

# ----------------------------------------------------------------------------------------- formatting
UNICODE = {"±": r"$\pm$", "≥": r"$\geq$", "≤": r"$\leq$", "σ": r"$\sigma$", "−": "-", "–": "--", "—": "---",
           "→": r"$\rightarrow$", "×": r"$\times$", "≈": r"$\approx$", "Δ": r"$\Delta$", "ε": r"$\epsilon$"}


def esc(text: str) -> str:
    """Escape plain text for LaTeX."""
    out = []
    for ch in text:
        if ch in "&%$#_{}":
            out.append("\\" + ch)
        elif ch == "\\":
            out.append(r"\textbackslash{}")
        elif ch == "~":
            out.append(r"\textasciitilde{}")
        elif ch == "^":
            out.append(r"\textasciicircum{}")
        elif ch in UNICODE:
            out.append(UNICODE[ch])
        else:
            out.append(ch)
    s = "".join(out)
    s = s.replace("->", r"$\rightarrow$").replace(">=", r"$\geq$").replace("<=", r"$\leq$")
    return s


def finite(x):
    return x is not None and not (isinstance(x, float) and (math.isnan(x) or math.isinf(x)))


def pct(x, d=1):
    return f"{100 * x:.{d}f}" if finite(x) else "n/a"


def pm(values, d=1):
    v = np.asarray(values, dtype=float)
    if len(v) > 1:
        return f"{100 * v.mean():.{d}f}$\\pm${100 * v.std(ddof=1):.{d}f}"
    return f"{100 * v.mean():.{d}f}"


def pm_str(cell, d=1):
    """'0.5520 ± 0.0040' or '0.5520' (fractions) -> percent string."""
    parts = [float(p) for p in str(cell).replace("±", " ").split()]
    if len(parts) == 2:
        return f"{100 * parts[0]:.{d}f}$\\pm${100 * parts[1]:.{d}f}"
    return f"{100 * parts[0]:.{d}f}"


def pp(x, d=1):
    return f"{100 * x:+.{d}f}" if finite(x) else "n/a"


def f2(x, d=2):
    return f"{x:.{d}f}" if finite(x) else "n/a"


def mse3(x, d=2):
    return f"{1000 * x:.{d}f}" if finite(x) else "n/a"


def ep(x):
    return f"{x:g}" if finite(x) else "never"


def commas(n):
    return f"{int(n):,}"


def macs(n):
    return f"{n / 1e6:.2f}M"


class Defs:
    def __init__(self):
        self.d = {}

    def set(self, key, value):
        self.d[key] = str(value)

    def write(self, path):
        lines = ["% Generated by scripts/build_report.py -- do not edit by hand."]
        for k, v in sorted(self.d.items()):
            lines.append(f"\\expandafter\\def\\csname res@{k}\\endcsname{{{v}}}")
        path.write_text("\n".join(lines) + "\n")


def write_text(name, paragraphs):
    lead = re.compile(r"^(\((a|b|c)\)\s*|Conclusion linking the three experiments:\s*)")
    body = "\n\n".join(esc(lead.sub("", p.strip())) for p in paragraphs if p.strip())
    (GEN / f"txt_{name}.tex").write_text(body + "\n")


# ----------------------------------------------------------------------------------------- static values
MLP_WIDTHS = {"MLP-S": 128, "MLP-M": 305, "MLP-L": 1024, "MLP-XL": 2048}
CNN_PARAMS, CNN_MACS = 1_130_378, 133_007_872
BOTTLENECKS = [16, 128, 1024]


def static_values(defs):
    """Architecture facts that do not depend on any experiment (verified against the notebooks' tables)."""
    for m, w in MLP_WIDTHS.items():
        for suffix in ("", "-perm") if m == "MLP-M" else ("",):
            defs.set(f"q1.{m}{suffix}.params", commas(2 * w * w + 3091 * w + 10))
            defs.set(f"q1.{m}{suffix}.macs", macs(3072 * w + 2 * w * w + 10 * w))
    for m in ("CNN", "CNN-perm"):
        defs.set(f"q1.{m}.params", commas(CNN_PARAMS))
        defs.set(f"q1.{m}.macs", macs(CNN_MACS))
    for d in BOTTLENECKS:
        defs.set(f"q3.ae{d}.params", commas(1_384_195 + 8193 * d))
        defs.set(f"q3.ae{d}.enc", commas(690_432 + 4097 * d))
        defs.set(f"q3.ae{d}.dec", commas(693_763 + 4096 * d))
        defs.set(f"q3.ae{d}.comp", f"{3072 / d:.0f}$\\times$")


# ----------------------------------------------------------------------------------------- Q1
def q1(defs, d: Path, figs):
    s = json.loads((d / "results_summary.json").read_text())
    defs.set("seed", s["seed"])
    defs.set("splitstate", s["split_random_state"])
    spec = pd.read_csv(d / "table_a1_model_specs.csv", index_col="model")
    val = pd.read_csv(d / "table_a3_validation_summary.csv", index_col="model")
    for m in spec.index:
        k = f"q1.{m}"
        defs.set(k + ".params", commas(spec.loc[m, "parameters"]))
        defs.set(k + ".macs", macs(spec.loc[m, "MACs_per_image"]))
        defs.set(k + ".lr", f"{val.loc[m, 'selected_lr']:g}")
        defs.set(k + ".val", pm_str(f"{val.loc[m, 'val_acc_mean']} {val.loc[m, 'val_acc_sd']}")
                 if finite(val.loc[m, "val_acc_sd"]) else pct(val.loc[m, "val_acc_mean"]))
        defs.set(k + ".trainfit", pct(val.loc[m, "train_acc_final"]))
        defs.set(k + ".gap", pp(val.loc[m, "gap_at_best"]))
        defs.set(k + ".bestep", f"{val.loc[m, 'best_epoch_mean']:.0f}")
        defs.set(k + ".test", pm(s["test_q1a"][m]))
    E, ET = s["evidence_validation"], s["evidence_test"]
    for key, src in [("cnnminusmlp", "cnn_minus_mlp"), ("permmlp", "perm_effect_mlp"), ("permcnn", "perm_effect_cnn"),
                     ("permgap", "cnnperm_minus_mlpperm"), ("interaction", "interaction"),
                     ("capgain", "capacity_gain_S_to_XL")]:
        defs.set(f"q1.ev.{key}.val", pp(E[src]))
        defs.set(f"q1.ev.{key}.test", pp(ET[src]))
    defs.set("q1.ev.mlptrainfit", pct(E["mlp_train_final"]))
    defs.set("q1.ev.mlpval", pct(E["mlp_val"]))
    defs.set("q1.ev.slope", pp(E["capacity_slope_per_doubling"]))
    defs.set("q1.ev.seedsd", f2(100 * E["seed_sd"]) if finite(E["seed_sd"]) else "n/a")
    defs.set("q1.ev.ratio", f"{E['param_ratio_S_to_XL']:.0f}")

    B = s["q1b"]
    for key, src, fmt in [("tpeak", "t_peak", ep), ("tmem", "t_mem", ep), ("valpeak", "val_peak", pct),
                          ("valend", "val_end", pct), ("memend", "mem_rate_end", pct), ("shadowend", "shadow_end", pct),
                          ("excessend", "excess_end", pp), ("truepeak", "true_corr_peak", pct),
                          ("truemax", "true_corr_max", pct), ("trueend", "true_corr_end", pct),
                          ("cleanvalpeak", "clean_val_peak", pct), ("cleanvalend", "clean_val_end", pct),
                          ("cleanaccpeak", "clean_acc_peak", pct), ("excesspeak", "excess_peak", pp),
                          ("fracrise", "frac_of_rise_at_mem", f2), ("trueatmem", "true_corr_at_mem", pct),
                          ("valatmem", "val_at_mem", pct), ("rho", "rho_excess_val_post_peak", f2)]:
        defs.set(f"q1b.{key}", fmt(B.get(src)) if B.get(src) is not None else "n/a")
    sf = B.get("structure_first")
    defs.set("q1b.decision", "yes" if sf is True else "no" if sf is False else "undetermined")
    for rec in s["test_q1b"]:
        run = "noisy" if "corrupted" in rec["run"] else "clean"
        ck = "early" if rec["checkpoint"].startswith("early") else "final"
        k = f"q1b.test.{run}.{ck}"
        defs.set(k + ".ep", ep(rec["epoch"]))
        defs.set(k + ".val", pct(rec["val_acc"]))
        defs.set(k + ".test", pct(rec["test_acc"]))
        defs.set(k + ".fit", pct(rec["train_fit_assigned"]))
        if rec.get("corrupted_fit") is not None and finite(rec["corrupted_fit"]):
            defs.set(k + ".corrfit", pct(rec["corrupted_fit"]))
    b2 = pd.read_csv(d / "table_b2_stable_learning_time.csv", index_col="group")
    for key, grp in [("clean", "clean examples (noisy run)"), ("corrupted", "corrupted examples (noisy run)"),
                     ("same", "same images, true labels (clean control)"), ("other", "other images (clean control)")]:
        defs.set(f"q1b.med.{key}", ep(float(b2.loc[grp, "median_stable_epoch"])))
        defs.set(f"q1b.bypeak.{key}", pct(b2.loc[grp, "stably_fitted_by_peak"]))
        defs.set(f"q1b.byend.{key}", pct(b2.loc[grp, "stably_fitted_by_end"]))

    t = pd.read_csv(d / "table_b1_memorisation_trajectory.csv")
    t = t[~t["epoch"].isin([0.0, 0.5, 3.0]) | t["event"].fillna("").ne("")]
    rows = []
    for _, r in t.iterrows():
        ev = str(r["event"]) if isinstance(r["event"], str) else ""
        mark = ("$^\\dagger$" if "peak" in ev else "") + ("$^\\ast$" if "onset" in ev else "")
        rows.append(f"{r['epoch']:g}{mark} & {pct(r['val_acc'])} & {pct(r['val_acc_clean_control'])} & "
                    f"{pct(r['clean_acc'])} & {pct(r['true_acc_on_corrupted'])} & {pct(r['mem_rate'])} & "
                    f"{pct(r['shadow_rate'])} \\\\")
    head = ("\\begin{tabular}{@{}rrrrrrr@{}}\n\\toprule\n"
            "Epoch & Val & Val (clean run) & Clean train & True & Mem. & Shad. \\\\\n\\midrule\n")
    (GEN / "tab_q1b_milestones.tex").write_text(head + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    text = (d / "interpretation.txt").read_text()
    qa, qb = text.split("\n\nQ1(b)\n")
    write_text("q1a", qa.replace("Q1(a)\n", "", 1).split("\n\n"))
    write_text("q1b", qb.split("\n\n"))
    figs += ["fig_a0_permutation_examples.png", "fig_a1_curves_factorial.png", "fig_a2_curves_capacity.png",
             "fig_a3_capacity_and_factorial.png", "fig_b1_memorisation.png"]
    env = d / "environment_used.json"
    if env.exists():
        e = json.loads(env.read_text())
        for k in ("device", "torch", "torchvision", "cuda", "python", "numpy", "scikit_learn"):
            defs.set(f"env.{k}", esc(str(e.get(k))))


# ----------------------------------------------------------------------------------------- Q2
Q2_CONDS = ["clean", "perm", "tile16", "tile8", "tile4"]


def q2(defs, d: Path, figs):
    s = json.loads((d / "results_summary.json").read_text())
    acc = {k: np.asarray(v) for k, v in s["test_acc_per_seed"].items()}
    for k, v in acc.items():
        arch, cond = k.split("|")
        defs.set(f"q2.{arch}.{cond}.test", pm(v))
    for cond in Q2_CONDS:
        if f"CNN|{cond}" in acc:
            defs.set(f"q2.gap.{cond}", pp(acc[f"CNN|{cond}"].mean() - acc[f"MLP-M|{cond}"].mean()))
    for cond, r in s["retention_R"].items():
        defs.set(f"q2.R.{cond}", f2(r) if r is not None else "n/a")
    for cond, r in s["confidence_retention_Rc"].items():
        defs.set(f"q2.Rc.{cond}", f2(r) if r is not None else "n/a")
    for k, m in s["metrics"].items():
        arch, cond = k.split("|")
        for name, src, fmt in [("confc", "conf_correct", f2), ("confw", "conf_wrong", f2), ("ece", "ece", f2),
                               ("auroc", "auroc_conf_vs_correct", f2), ("nll", "nll", f2),
                               ("meanconf", "mean_conf", f2)]:
            val = m.get(src)
            defs.set(f"q2.{arch}.{cond}.{name}", fmt(val) if val is not None else "n/a")
    for k, lr in s["selected_lr"].items():
        arch, cond = k.split("|")
        defs.set(f"q2.lr.{arch}.{cond}", f"{lr:g}")
    tr = pd.read_csv(d / "table_q2_transformations.csv", index_col="condition")
    for cond in tr.index:
        defs.set(f"q2.tr.{cond}.same", "yes" if bool(tr.loc[cond, "same_pixel_values"]) else "NO")
        defs.set(f"q2.tr.{cond}.unchanged", f2(tr.loc[cond, "positions_unchanged"]))
        for dist in (1, 2, 4, 8, 16):
            defs.set(f"q2.tr.{cond}.d{dist}", f2(tr.loc[cond, f"pairs_kept_d={dist}"]))
    for key in ("a", "b", "c", "link"):
        write_text(f"q2{key}", [s["conclusion"][key]])
    figs += ["fig_q2_0_conditions.png", "fig_q2_1_curves_clean.png", "fig_q2_2_first_layer_weights.png",
             "fig_q2_4_val_curves_all.png", "fig_q2_5_tile_curve.png", "fig_q2_6_reliability.png",
             "fig_q2_7_confidence_hist.png", "fig_q2_8_per_class.png", "fig_q2_9_confusion_cnn.png"]


# ----------------------------------------------------------------------------------------- Q3
Q3_SLUGS = ["clean", "noisy", "blur", "aenoisy", "daenoisy", "aeclean", "daeclean"]


def rep_slug(name):
    if name == "raw pixels":
        return "raw"
    m = re.match(r"random encoder d=(\d+)", name)
    if m:
        return "rand" + m.group(1)
    m = re.match(r"AE-(\d+)", name)
    if m:
        return "ae" + m.group(1)
    return "dae"


def q3(defs, d: Path, figs):
    s = json.loads((d / "results_summary.json").read_text())
    defs.set("q3.sel", s["selected_d"])
    defs.set("q3.sigma", f"{s['noise_sigma']:g}")
    defs.set("q3.blur", f"{s['blur_sigma']:g}")
    defs.set("q3.clf.lr", f"{s['classifier']['lr']:g}")
    a = pd.read_csv(d / "table_q3a_autoencoders_validation.csv", index_col="bottleneck_d")
    t = pd.read_csv(d / "table_q3a_test_reconstruction.csv", index_col="bottleneck_d")
    for dd in a.index:
        k = f"q3.ae{dd}"
        defs.set(k + ".params", commas(a.loc[dd, "parameters"]))
        defs.set(k + ".enc", commas(a.loc[dd, "encoder_params"]))
        defs.set(k + ".dec", commas(a.loc[dd, "decoder_params"]))
        vals = [float(p) for p in str(a.loc[dd, "val_mse"]).replace("±", " ").split()]
        defs.set(k + ".valmse", mse3(vals[0]) + (f"$\\pm${mse3(vals[1])}" if len(vals) > 1 else ""))
        defs.set(k + ".valpsnr", f2(a.loc[dd, "val_psnr_db"]))
        defs.set(k + ".bestep", f"{a.loc[dd, 'best_epoch']:.0f}")
        defs.set(k + ".conv", f"{100 * a.loc[dd, 'val_change_last5']:.1f}")
        tv = [float(p) for p in str(t.loc[dd, "test_mse"]).replace("±", " ").split()]
        defs.set(k + ".testmse", mse3(tv[0]) + (f"$\\pm${mse3(tv[1])}" if len(tv) > 1 else ""))
        defs.set(k + ".testpsnr", f2(t.loc[dd, "test_psnr_db"]))
    c = pd.read_csv(d / "table_q3b_test_classification.csv", index_col="condition")
    for slug, cond in zip(Q3_SLUGS, c.index):
        defs.set(f"q3.cls.{slug}.acc", pm_str(c.loc[cond, "classifier_acc"]))
        defs.set(f"q3.cls.{slug}.conf", f2(c.loc[cond, "mean_confidence"]))
        mse = c.loc[cond, "mse_to_clean"]
        defs.set(f"q3.cls.{slug}.mse", mse3(mse))
        defs.set(f"q3.cls.{slug}.psnr", f2(c.loc[cond, "psnr_db"]) if mse > 0 else "$\\infty$")
    defs.set("q3.F", f2(s["recovered_fraction"]) if s["recovered_fraction"] is not None else "n/a")
    defs.set("q3.decb", esc(s["decision_b"].lower()))
    for key, name in [("daenoisy", "DAE - corrupted"), ("daeae", "DAE - clean AE"), ("daeblur", "DAE - blur")]:
        lo, hi = s["bootstrap_ci"][name]
        defs.set(f"q3.ci.{key}", f"[{pp(lo)}, {pp(hi)}]")
    defs.set("q3.rho.lin", f2(s["spearman_linear"]) if s["spearman_linear"] is not None else "n/a")
    defs.set("q3.rho.knn", f2(s["spearman_knn"]) if s["spearman_knn"] is not None else "undefined")
    defs.set("q3.decc", esc(s["decision_c"].lower()))
    for key, r in s["representations"].items():
        name, inp = key.split("|")
        slugs = [rep_slug(name)] + (["aesel"] if name == f"AE-{s['selected_d']}" else [])
        for slug in slugs:
            k = f"q3.rep.{slug}.{inp}"
            defs.set(k + ".mse", mse3(r["test_mse_clean"]) if finite(r["test_mse_clean"]) else "--")
            for probe in ("linear_probe", "knn_probe"):
                sdv = r.get(probe + "_sd")
                defs.set(k + (".lin" if probe == "linear_probe" else ".knn"),
                         f"{100 * r[probe]:.1f}" + (f"$\\pm${100 * sdv:.1f}" if finite(sdv) else ""))
    for key in ("a", "b", "c"):
        write_text(f"q3{key}", [s["conclusion"][key]])
    figs += ["fig_q3_1_ae_training.png", "fig_q3_2_reconstructions.png", "fig_q3_3_denoising_examples.png",
             "fig_q3_4_severity.png", "fig_q3_5_recon_vs_probe.png"]


# ----------------------------------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", default=str(ROOT / "results"))
    ap.add_argument("--name", default=None)
    ap.add_argument("--roll", default=None)
    ap.add_argument("--repo", default=None)
    ap.add_argument("--commit", default=None, help="defaults to `git rev-parse HEAD` of this repository")
    ap.add_argument("--pending", action="store_true", help="ignore results/ and build the placeholder report")
    args = ap.parse_args()

    GEN.mkdir(parents=True, exist_ok=True)
    FIG.mkdir(parents=True, exist_ok=True)
    for f in list(GEN.glob("*.tex")) + list(FIG.glob("*.png")):
        f.unlink()

    defs, figs, status = Defs(), [], {}
    static_values(defs)
    res = Path(args.results)
    for q, fn in [("q1", q1), ("q2", q2), ("q3", q3)]:
        d = res / f"{q}_outputs"
        if args.pending or not (d / "results_summary.json").exists():
            status[q] = "pending (no results_summary.json)"
            continue
        qfigs = []
        fn(defs, d, qfigs)
        for f in qfigs:
            if (d / f).exists():
                shutil.copy(d / f, FIG / f)
        status[q] = f"filled from {d}"
    defs.write(GEN / "results.tex")

    commit = args.commit
    if commit is None:
        try:
            commit = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"], capture_output=True, text=True,
                                    check=True).stdout.strip()
            dirty = subprocess.run(["git", "-C", str(ROOT), "status", "--porcelain", "--", ".", ":!report"],
                                   capture_output=True, text=True).stdout.strip()
            if dirty:
                print("WARNING: uncommitted changes outside report/ -- commit them first so the hash matches the code.")
        except Exception:
            commit = None
    info = {"StudentName": args.name, "StudentRoll": args.roll, "RepoURL": args.repo, "CommitHash": commit}
    lines = ["% Generated by scripts/build_report.py"]
    for k, v in info.items():
        if k == "RepoURL" and v:
            lines.append(f"\\newcommand{{\\{k}}}{{\\url{{{v}}}}}")
        else:
            shown = esc(v) if v else PENDING
            lines.append(f"\\newcommand{{\\{k}}}{{{shown}}}")
    (GEN / "info.tex").write_text("\n".join(lines) + "\n")

    # Report every key the .tex files use but this build could not define
    used = set()
    for tex in [REPORT / "main.tex"] + list((REPORT / "sec").glob("*.tex")):
        used |= set(re.findall(r"\\res\{([^}]*)\}", tex.read_text()))
    missing = sorted(used - set(defs.d))
    for q, st in status.items():
        print(f"{q}: {st}")
    print(f"{len(defs.d)} values defined, {len(missing)} used in the report but still pending.")
    if missing and all(not s.startswith("pending") for s in status.values()):
        print("Undefined keys (check names):", ", ".join(missing[:40]))
    freeze = res / "q1_outputs" / "pip_freeze.txt"
    if freeze.exists() and not args.pending:
        shutil.copy(freeze, ROOT / "requirements.lock.txt")
        print("Wrote requirements.lock.txt (exact package versions of the run).")


if __name__ == "__main__":
    main()
