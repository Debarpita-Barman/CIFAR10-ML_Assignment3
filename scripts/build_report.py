#!/usr/bin/env python3
"""Collect the notebook outputs in results/ into the LaTeX report.

Every number in the report is written as \\res{key}. This script defines those keys from the files the
notebooks saved (results/q1_outputs, q2_outputs, q3_outputs), copies the figures into report/figures/ and
writes the generated interpretation paragraphs. Keys whose source files are missing stay undefined and
appear as a red "??" in the PDF, so a report built before the experiments have run cannot be mistaken
for a finished one.

Usage (from the repository root):
    python scripts/build_report.py --name "Your Name" --roll "21CS10045" \
        --repo "https://github.com/<user>/<repo>"            # commit hash is read from git
    cd report && latexmk -pdf main.tex
"""
import argparse
